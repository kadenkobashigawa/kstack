#!/usr/bin/env python3
"""
widget — builds what the animated widget shows: the house as a stack of image layers, the
sprites that move, the robot in parts, and each robot's route.

Usage
-----
    widget.py build <app-dir> [seed ...]    build the pool of houses into <app-dir>/build/

A house is generated by plans.py, furnished by furnish.py and drawn by layout.py. Each suite is
built on its own, cut to its own box but in the house's coordinates, so the page can stack the
first n suites for n runs: the floors, then the robots (driven by the page), then the furniture,
the lamp glow, the evening dimness and the walls. Only what moves stays separate: each plant (its
leaves sway), the cat (its ears twitch), the curtains (the page draws them), and the robot.

A route is worked out on the floor grid that rules.py's layout check builds: the robot's centre
may go wherever the nearest wall or footprint is more than its radius away. It sweeps the floor
in lanes, nearest lane next, travelling between lanes by the shortest path (A*) straightened
wherever the robot can see the next point. The page plans the way home itself, from wherever
the robot is when its run ends.
"""

from __future__ import annotations

import heapq
import json
import math
import sys
from pathlib import Path

import canvas
import layout
import pen
import vacuum



LANE = 30
CLEAR = vacuum.ROBOT_R + 5
RENDER_SCALE = 2


# ── routes ────────────────────────────────────────────────────────────────


def passable(g):
    """The cells the robot's centre may stand on."""
    return {c for c, dist in g['dist'].items() if dist > CLEAR}


def astar(ok, start, goal):
    """The shortest 8-connected path between two cells, or None."""
    if start not in ok or goal not in ok:
        return None
    frontier, came, cost = [(0.0, start)], {start: None}, {start: 0.0}
    while frontier:
        _, cur = heapq.heappop(frontier)
        if cur == goal:
            path = []
            while cur:
                path.append(cur)
                cur = came[cur]
            return path[::-1]
        for di in (-1, 0, 1):
            for dj in (-1, 0, 1):
                n = (cur[0] + di, cur[1] + dj)
                if (di or dj) and n in ok:
                    c = cost[cur] + math.hypot(di, dj)
                    if c < cost.get(n, 1e18):
                        cost[n], came[n] = c, cur
                        heapq.heappush(frontier, (c + math.dist(n, goal), n))
    return None


def sees(ok, a, b) -> bool:
    """Whether the robot can drive straight from one cell to another."""
    n = max(2, int(math.dist(a, b) * 2))
    return all((round(a[0] + (b[0] - a[0]) * t / n), round(a[1] + (b[1] - a[1]) * t / n)) in ok
               for t in range(n + 1))


def straighten(ok, path):
    """Drop every waypoint the robot can see past."""
    out, i = [path[0]], 0
    while i < len(path) - 1:
        j = len(path) - 1
        while j > i + 1 and not sees(ok, path[i], path[j]):
            j -= 1
        out.append(path[j])
        i = j
    return out


def nearest_ok(ok, cell):
    return min(ok, key=lambda c: math.dist(c, cell))


def coverage(g, start):
    """Lanes across the floor, LANE apart, each swept end to end; the nearest unswept lane end
    comes next, reached by the shortest straightened path."""
    ok = passable(g)
    step = max(1, round(LANE / g['cell']))
    runs = []
    for j in range(0, g['ny'], step):
        i = 0
        while i < g['nx']:
            if (i, j) in ok:
                k = i
                while (k + 1, j) in ok:
                    k += 1
                if k - i >= 3:
                    runs.append(((i, j), (k, j)))
                i = k + 1
            else:
                i += 1
    cur, route, left = nearest_ok(ok, start), [], set(range(len(runs)))
    route.append(cur)
    while left:
        best = min(((math.dist(cur, runs[r][e]), r, e) for r in left for e in (0, 1)))
        _, r, e = best
        left.discard(r)
        a, b = runs[r][e], runs[r][1 - e]
        path = astar(ok, cur, a)
        if path is None:
            continue
        route += straighten(ok, path)[1:] + [b]
        cur = b
    return route


# ── building the widget ───────────────────────────────────────────────────


def svg_box(svg: str, x, y, w, h) -> str:
    """The same SVG, cut down to one region of it."""
    head, rest = svg.split('>', 1)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{pen.f(x)} {pen.f(y)} {pen.f(w)} '
            f'{pen.f(h)}" width="{pen.f(w)}" height="{pen.f(h)}">' + rest)


LEAF_R = 50
ATLAS_COLS = 10


def atlas(sheet, leaves) -> str:
    """Every leaf of one plant on one sheet, each in its own cell centred on the point it hangs
    from, so one render makes them all."""
    cells = ''.join(
        f'<svg x="{(i % ATLAS_COLS) * 2 * LEAF_R}" y="{(i // ATLAS_COLS) * 2 * LEAF_R}" '
        f'width="{2 * LEAF_R}" height="{2 * LEAF_R}" '
        f'viewBox="{pen.f(px - LEAF_R)} {pen.f(py - LEAF_R)} {2 * LEAF_R} {2 * LEAF_R}">{markup}</svg>'
        for i, (px, py, markup) in enumerate(leaves))
    cols = min(ATLAS_COLS, len(leaves))
    rows = math.ceil(len(leaves) / ATLAS_COLS)
    w, h = cols * 2 * LEAF_R, rows * 2 * LEAF_R
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" '
            f'height="{h}"><style>{canvas.CSS}</style><defs>{"".join(sheet.defs)}</defs>{cells}</svg>')


def cut_atlas(png: Path, count: int, sid: str) -> None:
    """Cut a plant's leaf sheet back into one image per leaf."""
    from PIL import Image
    sheet = Image.open(png)
    cell = 2 * LEAF_R * RENDER_SCALE
    for i in range(count):
        x, y = (i % ATLAS_COLS) * cell, (i // ATLAS_COLS) * cell
        sheet.crop((x, y, x + cell, y + cell)).save(png.parent / f'{sid}-leaf-{i}.png')
    png.unlink()


def robot_parts(out: Path):
    """The robot's images: its body and a brush (they turn with it), its shine and its shadow
    (they stay put, so the light holds still while the robot turns), the ! that floats over a
    stopped run's robot, and that ! in ink for the hover slip."""
    R = vacuum.ROBOT_R
    parts = {}
    for name, ink in (('body', vacuum.robot(0, 'body')), ('brush', vacuum.robot(0, 'brush')),
                      ('alert', vacuum.alert()), ('alert-ink', vacuum.alert(fill=pen.C['line']))):
        sh = canvas.Sheet(ink.w + 4, ink.d + 4)
        sh.place(ink, 2, 2)
        parts[name] = (sh.svg(canvas.CSS, lit=False), ink.w + 4, ink.d + 4)
    disc = pen.smooth(pen.circle_pts(R + 2, R + 2, R, __import__('random').Random(1), 0.08, 26))
    sh = canvas.Sheet(2 * R + 4, 2 * R + 4)
    shine = (sh.crescent(disc, pen.shade_of(pen.C['rwhite']), -1.4, 'shade') +
             sh.crescent(disc, pen.light_of(pen.C['rwhite']), 0.63, 'light') +
             f'<path class="line" d="{disc}" fill="none" stroke="{pen.C["line"]}" stroke-width="1.3"/>')
    parts['shine'] = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {2 * R + 4} '
                      f'{2 * R + 4}" width="{2 * R + 4}" height="{2 * R + 4}"><style>{canvas.CSS}</style>'
                      f'<defs>{"".join(sh.defs)}</defs>{shine}</svg>', 2 * R + 4, 2 * R + 4)
    sh = canvas.Sheet(2 * R + 30, 2 * R + 30)
    blur = sh.blur(2.2)
    soft = sh.blur(1.3)
    shadow = (f'<circle class="ao" cx="{R + 15}" cy="{R + 15}" r="{R}" filter="url(#{blur})"/>'
              f'<circle class="cast" cx="{R + 16}" cy="{R + 16}" r="{R}" filter="url(#{soft})"/>')
    parts['shadow'] = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {2 * R + 30} '
                       f'{2 * R + 30}" width="{2 * R + 30}" height="{2 * R + 30}"><style>{canvas.CSS}'
                       f'</style><defs>{"".join(sh.defs)}</defs>{shadow}</svg>', 2 * R + 30,
                       2 * R + 30)
    jobs = []
    for name, (svg, w, h) in parts.items():
        p = (out / f'robot-{name}.svg').resolve()
        p.write_text(svg)
        jobs.append((str(p), w, h, 6))
    canvas.render(jobs)
    return {name: dict(src=f'robot-{name}.png', w=w, h=h) for name, (_, w, h) in parts.items()}


def build_suite(sheet, out: Path, box) -> dict:
    """One suite of a house, cut to its own box: its layers, the sprites that move, its robot and
    route, and its windows. Everything is in the house's coordinates."""
    out.mkdir(parents=True, exist_ok=True)
    layers, sprites = sheet.layers(canvas.CSS)
    jobs = []
    for name, svg in layers.items():
        p = (out / f'{name}.svg').resolve()
        p.write_text(svg_box(svg, *box))
        jobs.append((str(p), box[2], box[3], RENDER_SCALE))
    meta, atlases = [], []
    for sid, parts in sprites.items():
        info = sheet.sprites[sid]
        half = info.get('half', 95 if info['kind'] == 'sway' else 45)
        sbox = (info['cx'] - half, info['cy'] - half, 2 * half, 2 * half)
        p = (out / f'{sid}.svg').resolve()
        p.write_text(svg_box(parts['base'], *sbox))
        jobs.append((str(p), sbox[2], sbox[3], RENDER_SCALE))
        leaves = []
        if parts['leaves']:
            a = (out / f'{sid}-leaves.svg').resolve()
            a.write_text(atlas(sheet, parts['leaves']))
            cols = min(ATLAS_COLS, len(parts['leaves']))
            rows = math.ceil(len(parts['leaves']) / ATLAS_COLS)
            jobs.append((str(a), cols * 2 * LEAF_R, rows * 2 * LEAF_R, RENDER_SCALE))
            atlases.append((a, len(parts['leaves'])))
            leaves = [dict(src=f'{sid}-leaf-{i}.png', x=px - LEAF_R, y=py - LEAF_R, size=2 * LEAF_R)
                      for i, (px, py, _) in enumerate(parts['leaves'])]
        meta.append(dict(src=f'{sid}.png', x=sbox[0], y=sbox[1], w=sbox[2], h=sbox[3],
                         leaves=leaves, px=info['px'], py=info['py'], kind=info['kind'],
                         amp=info.get('amp'),
                         room=[(round(px - sbox[0], 1), round(py - sbox[1], 1))
                               for px, py in info['room']] if 'room' in info else None))
    canvas.render(jobs)
    for a, count in atlases:
        cut_atlas(a.with_suffix('.png'), count, a.stem.replace('-leaves', ''))
    for p in out.glob('*.svg'):
        p.unlink()
    ox, oy = sheet.offset
    su = sheet.suites[0]
    g = su['grid']
    ok = passable(g)
    dk, dx, dy, drot = su['dock']
    hx, hy = canvas.mapper(dk, dx, dy, drot)(vacuum.DOCKED_AT)
    fx, fy = canvas.facing(drot)
    out_pt = (hx + fx * 75, hy + fy * 75)
    start = (int((out_pt[0] - g['x0']) / g['cell']), int((out_pt[1] - g['y0']) / g['cell']))
    route = [(round(g['x0'] + (c[0] + 0.5) * g['cell'] + ox, 1),
              round(g['y0'] + (c[1] + 0.5) * g['cell'] + oy, 1)) for c in coverage(g, start)]
    bits = ''.join('1' if (i, j) in ok else '0' for j in range(g['ny']) for i in range(g['nx']))
    robot = dict(hood=(round(hx + ox, 1), round(hy + oy, 1)),
                 out=(round(out_pt[0] + ox, 1), round(out_pt[1] + oy, 1)),
                 heading=math.degrees(math.atan2(fx, -fy)), route=route,
                 grid=dict(x0=g['x0'] + ox, y0=g['y0'] + oy, cell=g['cell'], nx=g['nx'],
                           ny=g['ny'], bits=bits))
    return dict(box=box, layers=list(layers), sprites=meta, robot=robot,
                windows=[dict(a=a, b=b, n=into) for a, b, into in sheet.curtain_windows])


def build_house(seed, out: Path) -> dict:
    """A generated house, every suite furnished and built on its own and listed in the order the
    page shows them (plans.sweep), so the page can show the first n of them for n runs."""
    import furnish
    import plans
    suites = furnish.house(seed)
    margin = 60
    xs = [x for su in suites for r in su['rooms'] for x, _ in r['poly']]
    ys = [y for su in suites for r in su['rooms'] for _, y in r['poly']]
    ox, oy = margin - min(xs), margin - min(ys)
    W, H = max(xs) - min(xs) + 2 * margin, max(ys) - min(ys) + 2 * margin
    built = []
    for k, su in enumerate(suites):
        sheet = layout.house_sheet([su], layered=True, frame=((ox, oy), (W, H)))
        qx = [x + ox for r in su['rooms'] for x, _ in r['poly']]
        qy = [y + oy for r in su['rooms'] for _, y in r['poly']]
        box = (min(qx) - 40, min(qy) - 40, max(qx) - min(qx) + 80, max(qy) - min(qy) + 80)
        info = build_suite(sheet, out / str(k), box)
        info['dir'] = f'{out.name}/{k}/'
        built.append(info)
        print(f'house {seed}: suite {k + 1} built', file=sys.stderr)
    return dict(seed=seed, w=W, h=H, suites=[built[i] for i in plans.generate(seed)['reveal']])


def main(argv: list[str]) -> int:
    if len(argv) < 3 or argv[1] != 'build':
        print(__doc__)
        return 2
    app = Path(argv[2])
    build = app / 'build'
    build.mkdir(parents=True, exist_ok=True)

    #a build made here is local, so build.sh never swaps it for a fetched pack...
    (build / '.pack').unlink(missing_ok=True)
    seeds = [int(a) for a in argv[3:]] or [1, 12, 14]
    data = dict(robot=dict(r=vacuum.ROBOT_R, hubs=vacuum.BRUSH_HUBS, parts=robot_parts(build)), houses=[])
    for seed in seeds:
        data['houses'].append(build_house(seed, build / f'house-{seed}'))
    (build / 'data.js').write_text('window.ROBOVAC = ' + json.dumps(data) + ';\n')
    print(build / 'data.js')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
